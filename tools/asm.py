#!/usr/bin/env python3
"""Tiny assembler for the protocol-emulator CPU.

Usage: asm.py OUT.v IN1.asm [IN2.asm ...]   (see tools/build_rom.sh)

Syntax: one instruction per line, `;` starts a comment, `label:` defines a label.
Numbers are decimal or 0x-hex. See docs/isa.md for the instruction set.
"""
import sys

ROM_DEPTH = 256  # 8-bit program counter

# mnemonic -> (opcode, operand names)
OPS = {
    "NOP":  (0xF, []),                      # extended family, sub-opcode 4
    "PIN":  (0x1, ["pin", "val"]),          # drive one output pin
    "OUT":  (0x2, ["imm8"]),                # drive all 8 output pins
    "WAIT": (0x3, ["n"]),                   # take 1+n cycles in total
    "JMP":  (0x4, ["addr"]),
    "JPIN": (0x5, ["pin", "val", "addr"]),  # jump if input pin == val (val=0 uses opcode 0x0)
    "LDA":  (0x6, ["imm8"]),
    "SHR":  (0x7, []),                      # C = A[0]; A >>= 1
    "OUTC": (0x8, ["pin"]),                 # output pin = C
    "LDX":  (0x9, ["imm8"]),
    "DJNZ": (0xA, ["addr"]),                # X -= 1; jump if X != 0
    "IN":   (0xB, []),                      # A = input pins [7:0]
    "SHL":  (0xC, []),                      # C = A[7]; A <<= 1
    "INB":  (0xD, ["pin"]),                 # A[0] = input pin
    "CALL": (0xE, ["addr"]),                # push return address, jump
    # extended family (opcode 0xF, sub-opcode in bits 11:8)
    "HALT": (0xF, []),                      # stop until reset
    "RET":  (0xF, []),                      # pop return address, jump
    "ODRV": (0xF, ["pin", "val"]),          # open-drain pin: val=0 pull low, val=1 release
    "ODRVC": (0xF, ["pin"]),                # open-drain pin: pull low if C=0, release if C=1
    "SEND": (0xF, []),                      # channel: send A (blocks while the channel is full)
    "RECV": (0xF, []),                      # channel: A = received byte (blocks while empty)
    "SPAWN": (0xF, ["thread", "addr"]),     # start thread 1..3 at addr
}


def num(tok, labels=None):
    if labels is not None and tok in labels:
        return labels[tok]
    return int(tok, 0)


def encode(mn, args, labels, lineno):
    op, names = OPS[mn]
    if len(args) != len(names):
        raise SystemExit(f"line {lineno}: {mn} takes {len(names)} operand(s), got {len(args)}")
    v = {n: num(a, labels) for n, a in zip(names, args)}

    def rng(name, hi):
        if not 0 <= v[name] <= hi:
            raise SystemExit(f"line {lineno}: {mn} operand '{name}'={v[name]} out of range 0..{hi}")

    w = op << 12
    if mn == "PIN":
        rng("pin", 7); rng("val", 1)
        w |= (v["pin"] << 8) | v["val"]
    elif mn in ("OUT", "LDA", "LDX"):
        rng("imm8", 255)
        w |= v["imm8"]
    elif mn == "WAIT":
        rng("n", 4095)
        w |= v["n"]
    elif mn in ("JMP", "DJNZ"):
        rng("addr", ROM_DEPTH - 1)
        w |= v["addr"]
    elif mn == "JPIN":
        rng("pin", 15); rng("val", 1); rng("addr", ROM_DEPTH - 1)
        a = v["addr"]
        # opcode carries the pin state; address = {bit 11, bits 6:0}
        w = ((0x5 if v["val"] else 0x0) << 12) | ((a >> 7) << 11) | (v["pin"] << 7) | (a & 0x7F)
    elif mn == "OUTC":
        rng("pin", 7)
        w |= v["pin"] << 8
    elif mn == "INB":
        rng("pin", 15)
        w |= v["pin"] << 7
    elif mn == "CALL":
        rng("addr", ROM_DEPTH - 1)
        w |= v["addr"]
    elif mn == "NOP":
        w |= 0x4 << 8
    elif mn == "RET":
        w |= 0x1 << 8
    elif mn == "ODRV":
        rng("pin", 7); rng("val", 1)
        w |= (0x2 << 8) | (v["val"] << 3) | v["pin"]
    elif mn == "ODRVC":
        rng("pin", 7)
        w |= (0x3 << 8) | v["pin"]
    elif mn == "SEND":
        w |= 0x5 << 8
    elif mn == "RECV":
        w |= 0x6 << 8
    elif mn == "SPAWN":
        rng("thread", 3); rng("addr", ROM_DEPTH - 1)
        w |= ((0x8 + v["thread"]) << 8) | v["addr"]
    return w


def assemble(text):
    labels, lines = {}, []
    for lineno, raw in enumerate(text.splitlines(), 1):
        line = raw.split(";")[0].strip()
        if not line:
            continue
        while ":" in line:
            lab, line = line.split(":", 1)
            lab = lab.strip()
            if lab in labels:
                raise SystemExit(f"line {lineno}: duplicate label '{lab}'")
            labels[lab] = len(lines)
            line = line.strip()
        if line:
            parts = line.replace(",", " ").split()
            mn = parts[0].upper()
            if mn not in OPS:
                raise SystemExit(f"line {lineno}: unknown instruction '{parts[0]}'")
            lines.append((mn, parts[1:], lineno))
    if len(lines) > ROM_DEPTH:
        raise SystemExit(f"program too long: {len(lines)} > {ROM_DEPTH} instructions")
    return [encode(mn, a, labels, ln) for mn, a, ln in lines], labels


def emit_verilog(words, src):
    out = [
        f"// GENERATED by tools/asm.py from {src} -- do not edit by hand.",
        "`default_nettype none",
        "",
        "module rom (",
        "    input  wire [7:0]  addr,",
        "    output reg  [15:0] data",
        ");",
        "  always @* begin",
        "    case (addr)",
    ]
    for i, w in enumerate(words):
        out.append(f"      8'd{i}: data = 16'h{w:04X};")
    out += [
        "      default: data = 16'hF000;  // HALT",
        "    endcase",
        "  end",
        "endmodule",
        "",
    ]
    return "\n".join(out)


def main():
    if len(sys.argv) < 3:
        raise SystemExit(__doc__)
    dst, srcs = sys.argv[1], sys.argv[2:]
    # Source files are concatenated in order; labels are global across files.
    text = "\n".join(open(s).read() for s in srcs)
    words, labels = assemble(text)
    open(dst, "w").write(emit_verilog(words, ", ".join(srcs)))
    print(f"assembled {len(words)} instructions from {len(srcs)} file(s) -> {dst}")


if __name__ == "__main__":
    main()
